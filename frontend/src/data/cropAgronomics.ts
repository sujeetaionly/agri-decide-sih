export const getDynamicCropDetail = (
  cropId: string,
  farmData?: Partial<FarmQuestionnaireState>
): FullCropDetail => {
  const raw = MASTER_CROP_MAP[cropId] || MASTER_CROP_MAP['SOYBEAN'];
  const soil = (farmData?.soilType || 'BLACK').toUpperCase();
  const water = (farmData?.waterCapacity || 'MEDIUM').toUpperCase();

  let suit = 80;

  if (soil === 'SANDY' || soil === 'RED') {
    if (cropId === 'GROUNDNUT') suit = 95;
    else if (cropId === 'BAJRA') suit = 93;
    else if (cropId === 'MOONG') suit = 90;
    else if (cropId === 'MUSTARD') suit = 85;
    else if (cropId === 'MAIZE') suit = 76;
    else if (cropId === 'WHEAT') suit = 74;
    else if (cropId === 'SOYBEAN') suit = 68;
    else if (cropId === 'COTTON') suit = 65;
    else if (cropId === 'PADDY') suit = 50;
    else suit = 75;
  } else if (soil === 'LOAM') {
    if (cropId === 'MAIZE') suit = 95;
    else if (cropId === 'WHEAT') suit = 93;
    else if (cropId === 'SOYBEAN') suit = 91;
    else if (cropId === 'MUSTARD') suit = 89;
    else if (cropId === 'CHANA') suit = 88;
    else if (cropId === 'GROUNDNUT') suit = 86;
    else if (cropId === 'BAJRA') suit = 82;
    else suit = 82;
  } else if (soil === 'CLAY') {
    if (cropId === 'PADDY') suit = water === 'HIGH' ? 96 : 84;
    else if (cropId === 'WHEAT') suit = 88;
    else if (cropId === 'SOYBEAN') suit = 86;
    else if (cropId === 'CHANA') suit = 85;
    else if (cropId === 'GROUNDNUT') suit = 64;
    else suit = 78;
  } else {
    // BLACK Soil
    if (cropId === 'SOYBEAN') suit = 95;
    else if (cropId === 'COTTON') suit = 93;
    else if (cropId === 'TUR') suit = 91;
    else if (cropId === 'CHANA') suit = 89;
    else if (cropId === 'MAIZE') suit = 88;
    else if (cropId === 'WHEAT') suit = 87;
    else if (cropId === 'GROUNDNUT') suit = 82;
    else suit = 82;
  }

  if (water === 'LOW') {
    if (cropId === 'BAJRA' || cropId === 'MOONG') suit += 3;
    if (cropId === 'COTTON' || cropId === 'SUGARCANE' || cropId === 'PADDY') suit -= 15;
  } else if (water === 'HIGH') {
    if (cropId === 'PADDY' || cropId === 'SUGARCANE' || cropId === 'WHEAT') suit += 4;
  }

  const finalSuit = Math.min(98, Math.max(50, suit));

  return {
    ...raw,
    suitability_pct: finalSuit,
  };
};